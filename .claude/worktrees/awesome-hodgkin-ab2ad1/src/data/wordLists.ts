export function getWordListsBySubject(subject: Subject): WordList[] {
  return presetWordLists.filter(l => l.subject === subject);
}

export function getAllWordsForSubject(subject: Subject): Word[] {
  return presetWordLists
    .filter(l => l.subject === subject)
    .flatMap(l => l.words);
}

/** Returns the preset list name that contains the given word text (case-insensitive for English). */
export function findWordInPresets(
  text: string,
  subject: Subject,
): { listId: string; listName: string } | null {
  const needle = text.trim().toLowerCase();
  for (const list of presetWordLists) {
    if (list.subject !== subject) continue;
    for (const w of list.words) {
      if (w.text.toLowerCase() === needle || w.text === text.trim()) {
        return { listId: list.id, listName: list.name };
      }
    }
  }
  return null;
}

export function getWordListById(id: string): WordList | undefined {
  return presetWordLists.find(l => l.id === id);
}

/** Build a virtual "全部" list combining all words for a subject. */
export function buildAllList(subject: Subject): WordList {
  return {
    id: `${subject}-all`,
    name: subject === 'chinese' ? '全部词语' : 'All Words',
    subject,
    isVirtual: true,
    words: getAllWordsForSubject(subject),
  };
}

/** Build a virtual list of all English words starting with `letter`. */
export function buildLetterList(letter: string): WordList {
  const upper = letter.toUpperCase();
  const words = presetWordLists
    .filter(l => l.subject === 'english')
    .flatMap(l => l.words)
    .filter(w => w.text.toUpperCase().startsWith(upper));
  return {
    id: `en-letter-${letter.toLowerCase()}`,
    name: `Letter ${upper}`,
    subject: 'english',
    isVirtual: true,
    words,
  };
}
